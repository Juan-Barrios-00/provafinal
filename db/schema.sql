-- Rode no Supabase: SQL Editor > New query
create table if not exists posts (
  id          bigint generated by default as identity primary key,
  title       varchar(150) not null,
  summary     varchar(300) not null,
  content     text         not null,
  category    varchar(50)  not null,
  author      varchar(80)  not null,
  cover_url   varchar(500),
  created_at  timestamptz  not null default now(),
  updated_at  timestamptz  not null default now()
);

create index if not exists idx_posts_category   on posts (lower(category));
create index if not exists idx_posts_created_at on posts (created_at desc);

-- O acesso e feito pelo back-end (usuario postgres). Bloqueia acesso direto pela API publica do Supabase:
alter table posts enable row level security;

